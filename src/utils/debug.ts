// ============================================
// DEBUG LOGGING - только для разработки
// ============================================
// Обёртка над console.log, которая молчит в продакшене. Vite подставляет
// import.meta.env.DEV = false при сборке, поэтому вызовы debug() не создают
// шума в консоли пользователя, но остаются полезны при `npm run dev`.
//
// Реальные ошибки (console.error) и предупреждения парсеров (console.warn)
// через этот хелпер НЕ проходят — их видно всегда.

export function debug(...args: unknown[]): void {
  if (import.meta.env.DEV) {
    console.log(...args);
  }
}
